export function resolveSandboxProfile(env = process.env) {
  const profile = env.FLUO_CLI_SANDBOX_PROFILE ?? 'full';
  if (!['full', 'smoke'].includes(profile)) throw new TypeError(`Unknown sandbox verification profile: ${profile}`);
  return profile;
}

function isPathInsideDirectory(parentDirectory, candidatePath) {
  const resolvedParentDirectory = resolve(parentDirectory);
  const resolvedCandidatePath = resolve(candidatePath);

  return resolvedCandidatePath === resolvedParentDirectory || resolvedCandidatePath.startsWith(resolvedParentDirectory + sep);
}

function resolveSandboxRoot(env) {
  const requestedSandboxRoot = env.FLUO_CLI_SANDBOX_ROOT ? resolve(env.FLUO_CLI_SANDBOX_ROOT) : undefined;

  if (requestedSandboxRoot && isPathInsideDirectory(repoRoot, requestedSandboxRoot)) {
    return {
      sandboxRoot: defaultSandboxRoot,
      warning: `Ignoring FLUO_CLI_SANDBOX_ROOT=${requestedSandboxRoot} because sandbox projects must live outside the repo workspace.`,
    };
  }

  return {
    sandboxRoot: requestedSandboxRoot ?? defaultSandboxRoot,
  };
}

const { sandboxRoot, warning: sandboxRootWarning } = resolveSandboxRoot(process.env);
const defaultProjectName = 'starter-app';

function resolveStarterArgsFromEnv(env) {
  return [
    '--starter', env.FLUO_CLI_SANDBOX_STARTER ?? 'standard',
    '--shape', env.FLUO_CLI_SANDBOX_SHAPE ?? 'application',
    '--transport', env.FLUO_CLI_SANDBOX_TRANSPORT ?? 'http',
    '--runtime', env.FLUO_CLI_SANDBOX_RUNTIME ?? 'node',
    '--platform', env.FLUO_CLI_SANDBOX_PLATFORM ?? 'fastify',
    '--tooling', 'standard',
  ];
}

function run(command, args, cwd) {
  const result = spawnSync(command, args, {
    cwd,
    stdio: 'inherit',
  });

  if (result.error) {
    throw result.error;
  }

  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} failed with exit code ${result.status ?? 1}.`);
  }
}

function log(message) {
  process.stdout.write(`[cli sandbox] ${message}\n`);
}

function resolveProjectName(argv) {
  const projectName = argv[0] || defaultProjectName;

  if (projectName.includes('/') || projectName.includes('\\') || projectName === '.' || projectName === '..') {
    throw new Error('Project name must be a simple directory name without path separators.');
  }

  return projectName;
}

function resolveProjectDirectory(projectName) {
  void projectName;
  return sandboxRoot;
}

function sandboxMetadataPath(projectDirectory) {
  return join(projectDirectory, sandboxMetadataFileName);
}

function isLegacySandboxDirectory(projectDirectory) {
  return existsSync(join(projectDirectory, defaultProjectName, 'package.json'));
}

function isManagedSandboxDirectory(projectDirectory) {
  return existsSync(sandboxMetadataPath(projectDirectory));
}

function isGeneratedSandboxDirectory(projectDirectory) {
  const packageJsonPath = join(projectDirectory, 'package.json');
  const readmePath = join(projectDirectory, 'README.md');

  if (!existsSync(packageJsonPath) || !existsSync(readmePath)) {
    return false;
  }

  try {
    return readFileSync(readmePath, 'utf8').includes('Generated by @fluojs/cli.');
  } catch {
    return false;
  }
}

function isTransientSandboxDirectory(projectDirectory) {
  const entries = readdirSync(projectDirectory, { withFileTypes: true });

  return entries.length > 0
    && entries.every((entry) => entry.isDirectory() && entry.name === 'node_modules');
}

function assertSafeToResetSandbox(projectDirectory) {
  const resolvedProjectDirectory = resolve(projectDirectory);

  if (!existsSync(resolvedProjectDirectory)) {
    return;
  }

  if (
    isManagedSandboxDirectory(resolvedProjectDirectory)
    || isLegacySandboxDirectory(resolvedProjectDirectory)
    || isGeneratedSandboxDirectory(resolvedProjectDirectory)
    || isTransientSandboxDirectory(resolvedProjectDirectory)
  ) {
    return;
  }

  if (readdirSync(resolvedProjectDirectory).length === 0) {
    return;
  }

  throw new Error(
    `Refusing to reset a non-sandbox directory at ${resolvedProjectDirectory}. Choose an empty path or a dedicated FLUO_CLI_SANDBOX_ROOT.`,
  );
}

function writeSandboxMetadata(projectDirectory, projectName) {
  writeFileSync(
    sandboxMetadataPath(projectDirectory),
    JSON.stringify(
      {
        createdBy: '@fluojs/cli local sandbox',
        projectName,
      },
      null,
      2,
    ) + '\n',
    'utf8',
  );
}

function assertInsideSandboxRoot(projectDirectory) {
  const resolvedSandboxRoot = resolve(sandboxRoot);
  const resolvedProjectDirectory = resolve(projectDirectory);

  if (!isPathInsideDirectory(resolvedSandboxRoot, resolvedProjectDirectory)) {
    throw new Error(`Refusing to operate outside sandbox root: ${resolvedProjectDirectory}`);
  }
}

function logSandboxRoot() {
  if (sandboxRootWarning) {
    log(sandboxRootWarning);
  }

  log(`Using sandbox root ${sandboxRoot}`);
}

function cleanSandbox(projectDirectory) {
  assertInsideSandboxRoot(projectDirectory);
  assertSafeToResetSandbox(projectDirectory);
  rmSync(projectDirectory, { force: true, recursive: true });
}

function verifySandboxExists(projectDirectory) {
  if (!existsSync(join(projectDirectory, 'package.json'))) {
    throw new Error(
      `Sandbox project not found at ${projectDirectory}. Run \`pnpm sandbox:create\` first or use \`pnpm sandbox:test\`.`,
    );
  }
}

async function loadRunCli() {
  if (!runCliPromise) {
    runCliPromise = (async () => {
      log('Building @fluojs/cli dist for the local harness');
      run('pnpm', ['build'], packageRoot);

      const cliModuleUrl = pathToFileURL(join(packageRoot, 'dist', 'cli.js')).href;
      const cliModule = await import(cliModuleUrl);

      if (typeof cliModule.runCli !== 'function') {
        throw new Error('Unable to load runCli from packages/cli/dist/cli.js.');
      }

      return cliModule.runCli;
    })();
  }

  return runCliPromise;
}

async function withStarterEnv(envOverrides, action) {
  const keys = [
    'FLUO_CLI_SANDBOX_PLATFORM',
    'FLUO_CLI_SANDBOX_RUNTIME',
    'FLUO_CLI_SANDBOX_SHAPE',
    'FLUO_CLI_SANDBOX_STARTER',
    'FLUO_CLI_SANDBOX_TRANSPORT',
  ];
  const previous = new Map(keys.map((key) => [key, process.env[key]]));

  for (const key of keys) {
    const next = envOverrides[key];

    if (typeof next === 'string') {
      process.env[key] = next;
      continue;
    }

    delete process.env[key];
  }

  try {
    return await action();
  } finally {
    for (const key of keys) {
      const value = previous.get(key);

      if (typeof value === 'string') {
        process.env[key] = value;
        continue;
      }

      delete process.env[key];
    }
  }
}

async function runRepresentativeStarterSmokeMatrix() {
  for (const scenario of representativeStarterSmokeScenarios) {
    await withStarterEnv(scenario.env, async () => {
      log(`Running representative starter smoke: ${scenario.label}`);
      await createSandboxProject(scenario.projectName);
      await verifySandboxProject(scenario.projectName);
    });
  }
}

async function createSandboxProject(projectName) {
  const projectDirectory = resolveProjectDirectory(projectName);
  const runCli = await loadRunCli();
  const starterArgs = resolveStarterArgsFromEnv(process.env);

  log(`Refreshing sandbox at ${projectDirectory}`);
  cleanSandbox(projectDirectory);

  const exitCode = await runCli(
    [
      'new',
      projectName,
      '--package-manager',
      'pnpm',
      '--no-install',
      '--no-git',
      '--target-directory',
      projectDirectory,
      ...starterArgs,
    ],
    {
      cwd: sandboxRoot,
      dependencySource: 'local',
      repoRoot,
    },
  );

  if (exitCode !== 0) {
    throw new Error(`runCli returned a non-zero exit code: ${exitCode}.`);
  }

  const dependencyMode = process.env.FLUO_CLI_SANDBOX_DEPENDENCIES ?? 'fresh';
  if (!['fresh', 'locked'].includes(dependencyMode)) throw new TypeError(`Unknown starter dependency mode: ${dependencyMode}`);
  const dependencyEvidence = prepareStarterDependencies(projectDirectory, dependencyMode === 'locked'
    ? join(repoRoot, 'tooling/cli/verification-locks', `${projectName}.json`) : undefined);
  run('pnpm', ['install', ...(dependencyMode === 'locked' ? ['--frozen-lockfile'] : [])], projectDirectory);
  process.stdout.write(`${JSON.stringify({ starter: projectName, dependencyEvidence })}\n`);
  writeSandboxMetadata(projectDirectory, projectName);
  log(`Sandbox project is ready at ${projectDirectory}`);
  return projectDirectory;
}

function waitForDevReady(child, marker) {
  return new Promise((resolve, reject) => {
    let output = '';
    const timeout = setTimeout(() => finish(new Error(`fluo dev did not report "${marker}" within 60 seconds.`)), 60_000);
    const onData = (chunk) => {
      output = (output + String(chunk)).slice(-4096);
      if (output.includes(marker)) {
        finish();
      }
    };
    const onClose = (code) => finish(new Error(`fluo dev exited before readiness with code ${code}.`));
    const finish = (error) => {
      clearTimeout(timeout);
      child.stdout.off('data', onData);
      child.off('close', onClose);
      if (error) reject(error);
      else resolve();
    };
    child.stdout.on('data', onData);
    child.once('close', onClose);
  });
}

async function availablePort() {
  const server = createServer();
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  const address = server.address();
  if (typeof address !== 'object' || address === null) {
    throw new Error('Expected an ephemeral TCP port for the React dev fixture.');
  }
  const closed = once(server, 'close');
  server.close();
  await closed;
  return address.port;
}

function requestTcpSum(port) {
  return new Promise((resolve, reject) => {
    const socket = createConnection({ host: '127.0.0.1', port });
    const signal = AbortSignal.timeout(10_000);
    let response = '';
    const finish = (error, value) => {
      signal.removeEventListener('abort', onTimeout);
      socket.removeAllListeners();
      socket.destroy();
      if (error) reject(error);
      else resolve(value);
    };
    const onTimeout = () => finish(new Error('TCP starter did not answer math.sum within 10 seconds.'));
    signal.addEventListener('abort', onTimeout, { once: true });
    socket.once('error', finish);
    socket.once('connect', () => {
      socket.write(`${JSON.stringify({ kind: 'message', pattern: 'math.sum', payload: { a: 3, b: 5 }, requestId: 'sandbox-dev' })}\n`);
    });
    socket.on('data', (chunk) => {
      response += String(chunk);
      const newline = response.indexOf('\n');
      if (newline >= 0) {
        const packet = JSON.parse(response.slice(0, newline));
        finish(undefined, packet.payload);
      }
    });
  });
}

async function verifyStandardColdDev(projectDirectory, starterContract) {
  assert.equal(existsSync(join(projectDirectory, 'dist')), false, `${starterContract} dev must start without application dist.`);
  const port = await availablePort();
  const microservicePort = await availablePort();
  const child = spawn(join(projectDirectory, 'node_modules', '.bin', 'fluo'), ['dev', '--reporter', 'pretty'], {
    cwd: projectDirectory,
    env: {
      ...process.env,
      CI: '1',
      MICROSERVICE_HOST: '127.0.0.1',
      MICROSERVICE_PORT: String(microservicePort),
      PORT: String(port),
    },
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  child.stdout.on('data', (chunk) => process.stdout.write(chunk));
  child.stderr.on('data', (chunk) => process.stderr.write(chunk));

  try {
    await waitForDevReady(
      child,
      starterContract === 'microservice' ? 'fluo microservice successfully started.' : 'Listening on http',
    );
    if (starterContract !== 'microservice') {
      const response = await fetch(`http://127.0.0.1:${port}/health`);
      assert.equal(response.status, 200, `${starterContract} HTTP health response`);
    }
    if (starterContract !== 'application') {
      assert.equal(await requestTcpSum(microservicePort), 8, `${starterContract} TCP math.sum response`);
    }
    assert.equal(existsSync(join(projectDirectory, 'dist')), false, `${starterContract} dev must not build production output.`);
    log(`Installed ${starterContract} fluo dev: cold response passed`);
  } finally {
    const closed = once(child, 'close', { signal: AbortSignal.timeout(10_000) });
    child.kill('SIGINT');
    const [code] = await closed;
    assert.equal(code, 0, `${starterContract} dev must release its watcher and child on shutdown.`);
    log(`Installed ${starterContract} fluo dev: shutdown passed`);
  }
}

export async function verifyReactColdDev(projectDirectory, profile = resolveSandboxProfile()) {
  assert.equal(existsSync(join(projectDirectory, 'dist')), false, 'React dev must start without application dist.');
  const port = await availablePort();
  const origin = `http://127.0.0.1:${port}`;
  const appPath = join(projectDirectory, 'src', 'app.ts');
  const pagePath = join(projectDirectory, 'src', 'page.tsx');
  const originalApp = readFileSync(appPath, 'utf8');
  const originalPage = readFileSync(pagePath, 'utf8');
  const child = spawn(join(projectDirectory, 'node_modules', '.bin', 'fluo'), ['dev', '--reporter', 'pretty'], {
    cwd: projectDirectory,
    env: { ...process.env, CI: '1', PORT: String(port) },
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  child.stdout.on('data', (chunk) => process.stdout.write(chunk));
  child.stderr.on('data', (chunk) => process.stderr.write(chunk));
  let browser;
  let page;
  const diagnostics = [];

  try {
    await waitForDevReady(child, 'React dev app ready');
    assert.equal(existsSync(join(projectDirectory, 'dist')), false, 'React dev must not generate the production application dist.');
    const initial = await fetch(`${origin}/products/sku-42?preview=true`);
    assert.equal(initial.status, 200);
    const html = await initial.text();
    assert.match(html, /Catalog item sku-42/u);
    const assets = [...html.matchAll(/(?:src|href)="(\/(?:assets|src)\/[^"]+)"/gu)].map((match) => match[1]);
    assert(assets.some((asset) => asset.includes('/src/entry-client.tsx')));
    for (const asset of assets) {
      assert.equal((await fetch(new URL(asset, origin))).status, 200, asset);
    }

    if (profile === 'full') {
      const requireFromProject = createRequire(join(projectDirectory, 'package.json'));
      const { chromium } = requireFromProject('@playwright/test');
      browser = await chromium.launch({ channel: 'chrome', headless: true });
      page = await browser.newPage();
      page.on('console', (message) => {
        if (message.type() === 'warning' || message.type() === 'error') diagnostics.push(message.text());
      });
      page.on('pageerror', (error) => diagnostics.push(error.message));
      await page.goto(`${origin}/products/sku-42?preview=true`);
      await page.getByRole('button', { name: 'Count: 0' }).click();
      await page.getByRole('button', { name: 'Count: 1' }).waitFor();
    }
    assert.equal(existsSync(join(projectDirectory, 'dist')), false, 'React edits must stay on the Vite development path.');

    const serverReady = waitForDevReady(child, 'React dev app ready');
    writeFileSync(appPath, originalApp.replace("@Router('/products')", "@Router('/dev-products')"));
    await serverReady;
    assert.equal((await fetch(`${origin}/dev-products/sku-42?preview=true`)).status, 200);

    const restoredReady = waitForDevReady(child, 'React dev app ready');
    writeFileSync(appPath, originalApp);
    await restoredReady;
    const clientReady = waitForDevReady(child, 'React dev app ready');
    writeFileSync(pagePath, originalPage.replace('Catalog item', 'Updated item'));
    await clientReady;
    const edited = await fetch(`${origin}/products/sku-42?preview=true`);
    assert.equal(edited.status, 200);
    assert.match(await edited.text(), /Updated item sku-42/u);
    if (page) {
      await page.goto(`${origin}/products/sku-42?preview=true`);
      await page.getByRole('heading', { name: 'Updated item sku-42' }).waitFor();
      await page.getByRole('button', { name: 'Count: 0' }).click();
      await page.getByRole('button', { name: 'Count: 1' }).waitFor();
    }
    assert.deepEqual(diagnostics, []);
    log(`Installed React fluo dev: cold HTTP, assets, server/client edits passed (${profile})`);
  } finally {
    try {
      await browser?.close();
      const closed = once(child, 'close', { signal: AbortSignal.timeout(10_000) });
      child.kill('SIGINT');
      const [code] = await closed;
      assert.equal(code, 0, 'React dev must exit cleanly after watcher and child shutdown.');
      log('Installed React fluo dev: watcher and child shutdown passed');
    } finally {
      writeFileSync(appPath, originalApp);
      writeFileSync(pagePath, originalPage);
    }
  }
}

async function verifySandboxProject(projectName) {
  const projectDirectory = resolveProjectDirectory(projectName);
  verifySandboxExists(projectDirectory);
  const packageJson = JSON.parse(readFileSync(join(projectDirectory, 'package.json'), 'utf8'));
  const hasHttpStarter = Boolean(packageJson.dependencies?.['@fluojs/http']);
  const hasMicroserviceStarter = Boolean(packageJson.dependencies?.['@fluojs/microservices']);
  const hasReactViteSsrStarter = Boolean(packageJson.dependencies?.['@fluojs/react']);
  const starterContract = hasReactViteSsrStarter
    ? 'react-vite-ssr'
    : hasHttpStarter && hasMicroserviceStarter
    ? 'mixed'
    : hasMicroserviceStarter
      ? 'microservice'
      : 'application';

  if (starterContract === 'microservice' || starterContract === 'mixed') {
    if (!existsSync(join(projectDirectory, 'src', 'math', 'math.handler.test.ts'))) {
      throw new Error(`Expected the ${starterContract} starter scaffold to include src/math/math.handler.test.ts.`);
    }
  }

  if (starterContract === 'application' && !existsSync(join(projectDirectory, 'test', 'app.e2e.test.ts'))) {
    throw new Error('Expected the starter scaffold to include test/app.e2e.test.ts.');
  }

  if (starterContract === 'react-vite-ssr' && !existsSync(join(projectDirectory, 'tests', 'production-hydration.spec.ts'))) {
    throw new Error('Expected the React SSR + Vite starter to include its production hydration browser test.');
  }

  if (starterContract !== 'react-vite-ssr' && !existsSync(join(projectDirectory, 'vite.config.ts'))) {
    throw new Error('Expected the starter scaffold to include vite.config.ts.');
  }

  if (starterContract === 'microservice' || starterContract === 'mixed') {
    const mainFile = readFileSync(join(projectDirectory, 'src', 'main.ts'), 'utf8');

    if (starterContract === 'microservice' && !mainFile.includes('createMicroservice')) {
      throw new Error('Expected the microservice starter main.ts to bootstrap FluoFactory.createMicroservice(...).');
    }

    if (
      starterContract === 'mixed'
      && (!mainFile.includes('await app.connectMicroservice();') || !mainFile.includes('await app.startAllMicroservices();'))
    ) {
      throw new Error('Expected the mixed starter main.ts to attach and start the TCP microservice from the HTTP app bootstrap.');
    }

  }

  const configPaths = starterContract === 'react-vite-ssr'
    ? ['tsconfig.json', 'vite.client.config.ts', 'vite.server.config.ts', 'vitest.config.ts']
    : ['tsconfig.json', 'tsconfig.build.json', 'vite.config.ts', 'vitest.config.ts'];

  for (const configPath of configPaths) {
    const content = readFileSync(join(projectDirectory, configPath), 'utf8');
    if (content.includes('baseUrl')) {
      throw new Error(`Expected ${configPath} to avoid deprecated baseUrl aliasing.`);
    }
  }

  if (starterContract === 'react-vite-ssr') {
    log('Checking cold installed React dev before any application build');
    await verifyReactColdDev(projectDirectory);
    const previousServerCommand = process.env.FLUO_REACT_STARTER_SERVER_COMMAND;
    process.env.FLUO_REACT_STARTER_SERVER_COMMAND = 'dev';

    try {
      if (resolveSandboxProfile() === 'full') {
        log('Running the generated React development command through the first-page browser scenario');
        run('pnpm', ['test:browser'], projectDirectory);
      }
    } finally {
      if (previousServerCommand === undefined) {
        delete process.env.FLUO_REACT_STARTER_SERVER_COMMAND;
      } else {
        process.env.FLUO_REACT_STARTER_SERVER_COMMAND = previousServerCommand;
      }
    }
  } else if (
    !packageJson.dependencies?.['@fluojs/platform-bun']
    && !packageJson.dependencies?.['@fluojs/platform-deno']
    && !packageJson.dependencies?.['@fluojs/platform-cloudflare-workers']
  ) {
    log(`Checking cold installed ${starterContract} dev before any application build`);
    await verifyStandardColdDev(projectDirectory, starterContract);
  }

  log('Running generated project checks');
  if (hasHttpStarter) {
    const fixtureDirectory = join(repoRoot, 'tooling', 'cli', 'fixtures');
    cpSync(join(fixtureDirectory, 'generated-request-dto.ts.fixture'), join(projectDirectory, 'src', 'toolchain.dto.ts'));
    cpSync(join(fixtureDirectory, 'generated-request-dto.test.ts.fixture'), join(projectDirectory, 'src', 'toolchain.dto.test.ts'));
  }
  run('pnpm', ['typecheck'], projectDirectory);
  run('pnpm', ['build'], projectDirectory);
  run('pnpm', ['test'], projectDirectory);
  if (hasHttpStarter) {
    log('Building and executing decorated DTO field bindings through the generated Vite config');
    run('pnpm', [
      'exec', 'vite', 'build',
      '--config', hasReactViteSsrStarter ? 'vite.server.config.ts' : 'vite.config.ts',
      '--ssr', 'src/toolchain.dto.ts',
      '--outDir', '.fluo/toolchain',
    ], projectDirectory);
    run('node', [
      '--input-type=module',
      '-e',
      "const { verifyGeneratedDtoBinding } = await import('./.fluo/toolchain/main.js'); await verifyGeneratedDtoBinding(); console.log('Generated Vite DTO field binding passed');",
    ], projectDirectory);
  }
  if (starterContract === 'react-vite-ssr' && resolveSandboxProfile() === 'full') {
    run('pnpm', ['test:browser'], projectDirectory);
  }

  log('Checking installed CLI command paths inside the sandbox project');
  if (!existsSync(join(projectDirectory, 'node_modules', '.bin', 'fluo'))) {
    throw new Error('Expected the installed CLI to expose node_modules/.bin/fluo.');
  }

  run('pnpm', ['exec', 'fluo', 'g', 'repo', 'User'], projectDirectory);
  run('pnpm', ['exec', 'fluo', '--help'], projectDirectory);

  if (!existsSync(join(projectDirectory, 'src', 'users', 'user.repo.ts'))) {
    throw new Error('Expected the installed `fluo` command to generate src/users/user.repo.ts.');
  }

  if (!existsSync(join(projectDirectory, 'src', 'users', 'user.repo.slice.test.ts'))) {
    throw new Error('Expected the installed `fluo` command to generate src/users/user.repo.slice.test.ts.');
  }

  log('Re-running typecheck and test after generator output');
  run('pnpm', ['typecheck'], projectDirectory);
  run('pnpm', ['test'], projectDirectory);

  log('Sandbox verification passed');
}

function printUsage() {
  process.stdout.write(
    [
      'Usage: node ./scripts/local-test-env.mjs <create|verify|test|clean> [project-name]',
      'Use `matrix` to run the representative generated-project smoke suite (default app, React SSR + Vite, TCP microservice, mixed app).',
      'Defaults project-name to starter-app and uses the sandbox root itself as the generated app directory.',
      'Set FLUO_CLI_SANDBOX_ROOT to override the sandbox root outside the repo workspace.',
    ].join('\n') + '\n',
  );
}

async function main() {
  resolveSandboxProfile();
  const [command, ...rest] = process.argv.slice(2);
  const projectName = resolveProjectName(rest);
  const projectDirectory = resolveProjectDirectory(projectName);

  switch (command) {
    case 'create':
      logSandboxRoot();
      await createSandboxProject(projectName);
      break;
    case 'verify':
      logSandboxRoot();
      await verifySandboxProject(projectName);
      break;
    case 'test':
      logSandboxRoot();
      await createSandboxProject(projectName);
      await verifySandboxProject(projectName);
      break;
    case 'matrix':
      logSandboxRoot();
      await runRepresentativeStarterSmokeMatrix();
      break;
    case 'clean':
      logSandboxRoot();
      cleanSandbox(projectDirectory);
      log(`Removed ${projectDirectory}`);
      break;
    default:
      printUsage();
      process.exitCode = 1;
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
