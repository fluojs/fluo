import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { STARTER_PROFILE_REGISTRY } from '../src/new/starter-profiles.ts';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const generatedModulePath = join(repositoryRoot, 'packages', 'cli', 'src', 'new', 'published-internal-dependencies.ts');
const packageNames = [...new Set(STARTER_PROFILE_REGISTRY.flatMap(({ dependencies }) => [
  ...dependencies.dependencies,
  ...dependencies.devDependencies,
]))].filter((name) => name.startsWith('@fluojs/') && name !== '@fluojs/cli').sort();
const dependencyRanges = Object.fromEntries(packageNames.map((name) => {
  const packageJsonPath = join(repositoryRoot, 'packages', name.slice('@fluojs/'.length), 'package.json');
  const manifest = JSON.parse(readFileSync(packageJsonPath, 'utf8'));

  if (manifest.name !== name || typeof manifest.version !== 'string' || manifest.version.length === 0) {
    throw new TypeError(`Expected ${packageJsonPath} to declare ${name} and a non-empty string version.`);
  }

  return [name, `^${manifest.version}`];
}));

const generatedModule = [
  '// Generated by scripts/generate-published-internal-dependencies.mjs during the CLI build.',
  '/** Per-package release ranges for all published starter dependencies except the generator CLI itself. */',
  `export const PUBLISHED_INTERNAL_DEPENDENCIES = ${JSON.stringify(dependencyRanges, null, 2)} as const;`,
  '',
].join('\n');

if (!existsSync(generatedModulePath) || readFileSync(generatedModulePath, 'utf8') !== generatedModule) {
  writeFileSync(generatedModulePath, generatedModule, 'utf8');
}
