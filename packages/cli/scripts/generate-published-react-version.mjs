import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const reactPackageJsonPath = join(repositoryRoot, 'packages', 'react', 'package.json');
const generatedModulePath = join(repositoryRoot, 'packages', 'cli', 'src', 'new', 'published-react-version.ts');
const reactPackageJson = JSON.parse(readFileSync(reactPackageJsonPath, 'utf8'));

if (typeof reactPackageJson.version !== 'string') {
  throw new TypeError(`Expected ${reactPackageJsonPath} to declare a string version.`);
}

const generatedModule = [
  '// Generated by scripts/generate-published-react-version.mjs during the CLI build.',
  `export const PUBLISHED_REACT_VERSION = ${JSON.stringify(reactPackageJson.version)};`,
  '',
].join('\n');

if (readFileSync(generatedModulePath, 'utf8') !== generatedModule) {
  writeFileSync(generatedModulePath, generatedModule, 'utf8');
}
